import { test, expect } from '@playwright/test';

test('registration dashboard searches, optional guardian and repeatable printable stub', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/login');
  await page.getByLabel('Email address').fill('information@rhu.test');
  await page.getByLabel('Password', { exact: true }).fill('Password!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/dashboard/);
  await expect(page.getByRole('link', { name: 'Register new patient', exact: true })).toHaveCount(0);
  await expect(page.getByText('Consultation today', { exact: true })).toBeVisible();
  await page.goto('/patients');
  await page.getByLabel('Patient number or name', { exact: true }).fill('Fictional Dashboard Browser');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.getByRole('link', { name: 'Register patient', exact: true }).click();
  await page.getByLabel('First name', { exact: true }).fill('Fictional Dashboard');
  await page.getByLabel('Last name', { exact: true }).fill('Browser');
  await page.getByLabel('Date of birth', { exact: true }).fill('2000-01-10');
  await page.getByLabel('Sex', { exact: true }).selectOption('Female');
  await page.getByLabel('Barangay', { exact: true }).fill('Example Barangay');
  await page.getByLabel('Municipality', { exact: true }).fill('Calasiao');
  await page.getByLabel('Province', { exact: true }).fill('Pangasinan');
  await page.getByLabel('Name (optional)', { exact: true }).fill('Fictional Guardian');
  await page.locator('#emergency_contact_number').fill('000-TEST');
  await page.getByLabel('Guardian / contact name', { exact: true }).fill('Fictional Guardian');
  await page.getByLabel('Guardian contact number (optional)', { exact: true }).fill('000-TEST');
  await page.getByLabel('Relationship to patient', { exact: true }).fill('Parent');
  await page.getByRole('button', { name: 'Register patient', exact: true }).click();
  await expect(page).toHaveURL(/\/patients\/\d+$/);
  await expect(page.getByText('Fictional Guardian', { exact: true })).toHaveCount(2);
  await page.getByRole('link', { name: 'Start visit', exact: true }).click();
  await page.getByLabel('Requested service (required)').selectOption({ label: 'Consultation' });
  const serviceId = await page.getByLabel('Requested service (required)').inputValue();
  const queueInput = page.getByLabel('Queue number (auto-generated)');
  await expect(queueInput).toHaveAttribute('readonly', '');
  const queue = await queueInput.inputValue();
  expect(queue).toMatch(/^[A-Z]{2}-\d{4}$/);
  await page.getByRole('button', { name: 'Start visit', exact: true }).click();
  const visitUrl = page.url();
  await page.getByRole('link', { name: 'Print / Reprint stub', exact: true }).click();
  await expect(page).toHaveURL(/\/stub$/);
  await expect(page.getByText(queue, { exact: true })).toBeVisible();
  await expect(page.getByText('Fictional Guardian')).toHaveCount(0);
  await expect(page.getByRole('img', { name: 'RHU logo' })).toBeVisible();
  await page.emulateMedia({ media: 'print' });
  await page.setViewportSize({ width: 794, height: 1123 });
  await expect(page.getByRole('button', { name: 'Print stub' })).toBeHidden();
  await page.screenshot({ path: 'storage/framework/testing/visit-stub-print.png', fullPage: true });
  await page.emulateMedia({ media: 'screen' });
  await page.reload();
  await expect(page.getByText(queue, { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to visit' }).click();
  await expect(page).toHaveURL(visitUrl);
  const patientId = visitUrl.match(/patients\/(\d+)/)[1];
  const csrf = await page.locator('form[action$="/logout"] input[name="_token"]').inputValue();
  for (let i = 0; i < 24; i++) {
    const response = await page.request.post(`/patients/${patientId}/visits`, {
      form: { _token: csrf, service_id: serviceId, visit_date: new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Manila' }) },
    });
    expect(response.ok()).toBe(true);
  }
  await page.goto('/dashboard');
  await expect(page.locator('article')).toHaveCount(await page.locator('article a').count());
  await page.getByRole('link', { name: /^Visits today:/ }).click();
  await expect(page).toHaveURL(/#today-visits$/);
  await page.getByRole('link', { name: /^Consultation today:/ }).click();
  await expect(page).toHaveURL(/service_id=\d+#today-visits$/);
  await page.getByRole('link', { name: 'All services', exact: true }).click();
  const scrollArea = page.getByRole('region', { name: "Today's visits, scroll to load more" });
  const expectedTotal = parseInt(await page.locator('#today-visits-title + span').innerText(), 10);
  await expect(scrollArea.locator('tbody tr')).toHaveCount(20);
  await expect.poll(() => scrollArea.evaluate(el => {
    const table = el.querySelector('table');
    const expectedHeight = table.tHead.offsetHeight + Array.from(table.tBodies[0].rows).slice(0, 10).reduce((sum, row) => sum + row.offsetHeight, 0);
    return Math.abs(el.clientHeight - expectedHeight) <= 1 && el.scrollHeight > el.clientHeight;
  })).toBe(true);
  await scrollArea.evaluate(el => { el.scrollTop = el.scrollHeight; });
  await expect(scrollArea.locator('tbody tr')).toHaveCount(expectedTotal);
  await expect(scrollArea.getByRole('button', { name: 'Load more visits' })).toBeHidden();
  const totals = await page.locator('article').allTextContents();
  await page.locator('#today-search').fill(queue);
  await page.getByRole('button', { name: 'Search visits', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: queue })).toHaveCount(1);
  await expect(scrollArea).toHaveJSProperty('clientHeight', 744);
  expect(await page.locator('article').allTextContents()).toEqual(totals);
  await expect(page.getByLabel('Patient number or name', { exact: true })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'storage/framework/testing/dashboard-registration-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.locator('#today-search').fill('FICTIONAL-NO-MATCH-999');
  await page.getByRole('button', { name: 'Search visits', exact: true }).click();
  await expect(page.getByText('No matching visits.', { exact: true })).toBeVisible();
  await expect(scrollArea).toHaveJSProperty('clientHeight', 744);
  expect(errors).toEqual([]);
});
