test('pharmacist release and admin PDF download', async ({ page, browser }) => {
  await login(page, 'pharmacist');
  await page.goto('/pharmacy/1/visits/1');
  await page.getByLabel('Quantity released now', { exact: true }).fill('1');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Record release', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('release recorded');
  await expect(page.getByRole('heading', { name: 'Release history' })).toBeVisible();
  const context = await browser.newContext();
  const admin=await context.newPage();
  await login(admin,'admin');
  await admin.goto('/reports');
  const downloadPromise=admin.waitForEvent('download');
  await admin.getByRole('link',{name:'Download report PDF'}).click();
  const download=await downloadPromise;
  expect(download.suggestedFilename()).toBe('rhu-service-report.pdf');
  expect(await download.failure()).toBeNull();
  await admin.screenshot({path:'storage/framework/testing/admin-report.png',fullPage:true});
  await context.close();
});


