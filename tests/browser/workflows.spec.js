import { test, expect } from '@playwright/test';

async function login(page, account) {
  await page.goto('/login');
  await page.getByLabel('Email address').fill(account + '@rhu.test');
  await page.getByLabel('Password', { exact: true }).fill('Password!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/dashboard/);
}
test('desktop sidebar, service modal, alerts and logout', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await login(page, 'admin');
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  await expect(page.locator('body')).toHaveClass(/sidebar-collapsed/);
  await page.reload();
  await expect(page.locator('body')).toHaveClass(/sidebar-collapsed/);
  await page.locator('.sidebar-logo-toggle').click();
  await expect(page.locator('body')).not.toHaveClass(/sidebar-collapsed/);
  await page.getByRole('separator', { name: 'Resize sidebar' }).focus();
  await page.keyboard.press('End');
  await expect(page.getByRole('separator', { name: 'Resize sidebar' })).toHaveAttribute('aria-valuenow', '420');
  const handle = await page.getByRole('separator', { name: 'Resize sidebar' }).boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 100);
  await page.mouse.down();
  await page.mouse.move(handle.x + handle.width / 2 - 120, handle.y + 100, { steps: 5 });
  await page.mouse.up();
  await expect(page.getByRole('separator', { name: 'Resize sidebar' })).toHaveAttribute('aria-valuenow', '300');
  await page.reload();
  await expect(page.getByRole('separator', { name: 'Resize sidebar' })).toHaveAttribute('aria-valuenow', '300');
  await page.goto('/services');
  const manageService = page.getByRole('button', { name: /^Manage service:/ }).first();
  await manageService.hover();
  await expect(manageService).toHaveCSS('cursor', 'pointer');
  await page.getByRole('button', { name: '+ Add service', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await dialog.getByLabel('Service name (required)').fill('Browser fictional service');
  await dialog.getByLabel('Code (required)').fill('BROWSER_TEST');
  await dialog.getByRole('button', { name: 'Add service', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Service');
  await page.getByRole('button', { name: 'Dismiss notification' }).click();
  await expect(page.getByRole('status')).toBeHidden();
  await page.getByRole('button', { name: 'Manage service: Browser fictional service', exact: true }).click();
  await dialog.getByLabel('Code (required)').fill('BROWSER_EDIT');
  await dialog.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.locator('tbody')).toContainText('BROWSER_EDIT');
  await page.getByRole('button', { name: 'Manage service: Browser fictional service', exact: true }).click();
  await dialog.getByRole('button', { name: 'Delete service', exact: true }).click();
  await dialog.getByRole('button', { name: 'Delete service', exact: true }).click();
  await expect(page.locator('tbody')).not.toContainText('Browser fictional service');
  await page.locator('[x-ref="accountButton"]').click();
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page).toHaveURL(/login/);
  expect(errors).toEqual([]);
});
